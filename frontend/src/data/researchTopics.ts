export function setupFromResearch(
  topic: ResearchTopic,
  age: AgeBand,
  turns: 5 | 10 | 15,
): InquirySetup {
  return {
    age_band: age,
    max_turns: turns,
    topic: topic.title,
    core_question: topic.question,
    inquiry_focus: topic.focus,
    background_info: topic.background,
    exclusions: '不使用真實同學的個人資料或經歷；維持在課程探究範圍。',
    opening_message: topic.opening,
  }
}
